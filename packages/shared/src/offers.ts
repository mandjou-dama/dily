import { z } from "zod";
import {
  DELIVERY_AREA_MAX_LENGTH,
  fulfilmentSchema,
  orderSchema,
} from "./orders";

/** Unanswered this long, an offer expires. */
export const OFFER_TTL_HOURS = 24;
/** After an accepted offer, the listing is held for the buyer this long, waiting for payment. */
export const RESERVATION_HOURS = 24;

export const offerStatuses = [
  "pending",
  "accepted",
  "declined",
  // A newer offer in the same conversation took its place
  "superseded",
  "expired",
] as const;
export const offerStatusSchema = z.enum(offerStatuses);
export type OfferStatus = z.infer<typeof offerStatusSchema>;

/**
 * A price proposed in a conversation, by the buyer or, in reply, the seller.
 * One amount: the total the buyer pays, delivery included.
 */
export const offerSchema = z.object({
  id: z.uuid(),
  conversationId: z.uuid(),
  authorId: z.uuid(),
  amount: z.number().int(),
  fulfilment: fulfilmentSchema,
  // The listing's delivery fee when the offer was made; null for pickup
  deliveryFee: z.number().int().nullable(),
  // Where to deliver: "Hamdallaye ACI"; null for pickup
  deliveryArea: z.string().nullable(),
  // The listing's price at the time: plus `deliveryFee`, what the amount compares to
  listPrice: z.number().int(),
  status: offerStatusSchema,
  // Still pending past this, it's expired
  expiresAt: z.iso.datetime(),
  respondedAt: z.iso.datetime().nullable(),
  createdAt: z.iso.datetime(),
});
export type Offer = z.infer<typeof offerSchema>;

/** The listed price for a way of getting the item: what an offer compares to. */
export const listedTotal = ({
  listPrice,
  deliveryFee,
}: {
  listPrice: number;
  deliveryFee: number | null;
}) => listPrice + (deliveryFee ?? 0);

/**
 * `POST /conversations/:id/offers`: the buyer's offer, or a counter-offer
 * from either side. A seller's counter-offer keeps the way of getting the
 * item and the delivery area of the offer it answers.
 */
export const offerBodySchema = z.object({
  // Generated by the app: sending again after a network error never duplicates
  id: z.uuid(),
  amount: z.number().int().min(1).max(100_000_000),
  fulfilment: fulfilmentSchema,
  // Required for the buyer's delivery offers, ignored otherwise
  deliveryArea: z
    .string()
    .trim()
    .max(DELIVERY_AREA_MAX_LENGTH)
    .nullish()
    .transform((value) => value || null),
});
export type OfferBody = z.input<typeof offerBodySchema>;

/** `POST /offers/:id/accept`: the offer, and the order it started. */
export const acceptedOfferSchema = z.object({
  offer: offerSchema,
  order: orderSchema,
});
export type AcceptedOffer = z.infer<typeof acceptedOfferSchema>;
