import { z } from "zod";
import { productStatusSchema } from "./products";

/** Same limit as the `messages_body_check` constraint. */
export const MESSAGE_MAX_LENGTH = 4000;
export const MESSAGES_PAGE_SIZE = 30;
export const CONVERSATIONS_PAGE_SIZE = 20;

export const chatMessageSchema = z.object({
  id: z.uuid(),
  conversationId: z.uuid(),
  senderId: z.uuid(),
  body: z.string(),
  createdAt: z.iso.datetime(),
  // Set when the other participant opened the conversation
  readAt: z.iso.datetime().nullable(),
});
export type ChatMessage = z.infer<typeof chatMessageSchema>;

/** A conversation as the signed-in user sees it: about one listing, with one other person. */
export const conversationSchema = z.object({
  id: z.uuid(),
  product: z.object({
    id: z.uuid(),
    title: z.string(),
    price: z.number().int(),
    status: productStatusSchema,
    // The cover image
    imagePath: z.string().nullable(),
  }),
  otherUser: z.object({
    id: z.uuid(),
    name: z.string(),
    avatarPath: z.string().nullable(),
  }),
  // "buyer" when the signed-in user wrote to the seller
  role: z.enum(["buyer", "seller"]),
  lastMessage: chatMessageSchema.nullable(),
  // Messages from the other person not read yet
  unreadCount: z.number().int(),
});
export type Conversation = z.infer<typeof conversationSchema>;

export const conversationPageSchema = z.object({
  // Latest message first; conversations without any message are left out
  items: z.array(conversationSchema),
  nextCursor: z.string().nullable(),
});
export type ConversationPage = z.infer<typeof conversationPageSchema>;

export const messagePageSchema = z.object({
  // Newest first
  items: z.array(chatMessageSchema),
  nextCursor: z.string().nullable(),
});
export type MessagePage = z.infer<typeof messagePageSchema>;

/** "Message the seller": finds the buyer's conversation about the listing, or starts it. */
export const openConversationBodySchema = z.object({ productId: z.uuid() });

export const sendMessageBodySchema = z.object({
  // Generated by the app: sending again after a network error never duplicates
  id: z.uuid(),
  body: z.string().trim().min(1).max(MESSAGE_MAX_LENGTH),
});
export type SendMessageBody = z.input<typeof sendMessageBodySchema>;

export const unreadCountSchema = z.object({ count: z.number().int() });
